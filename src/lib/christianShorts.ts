function normalizeToken(value: string) {
  return normalizeMetadata(value)
    .trim()
    .replace(/^#+/, '')
    .replace(/[\s_.-]+/g, '')
}

function normalizeMetadata(value: string) {
  return decodeYouTubeText(value)
    .normalize('NFKC')
    .replace(/\p{Cf}/gu, '')
    .toLocaleLowerCase('ko-KR')
}

function extractHashtags(value: string) {
  return Array.from(value.matchAll(/#[\p{L}\p{N}_.-]+/gu), (match) => match[0])
}

function decodeYouTubeText(value: string) {
  return value
    .replaceAll('&amp;', '&')
    .replaceAll('&quot;', '"')
    .replaceAll('&#39;', "'")
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>')
    .replace(/&#(x[0-9a-f]+|\d+);/gi, (original, numeric: string) => {
      const isHex = numeric[0].toLowerCase() === 'x'
      const codePoint = Number.parseInt(isHex ? numeric.slice(1) : numeric, isHex ? 16 : 10)
      return codePoint > 0 && codePoint <= 0x10ffff ? String.fromCodePoint(codePoint) : original
    })
}

function isSafeYoutubeId(value: string) {
  return /^[A-Za-z0-9_-]{6,20}$/.test(value)
}

export function isSafeYouTubePageToken(value: string) {
  return /^[A-Za-z0-9_-]{1,256}$/.test(value)
}

export function parseYouTubeDuration(value: string | undefined) {
  if (!value) return 0

  const match = value.match(
    /^P(?:(\d+)D)?T(?:(\d+)H)?(?:(\d+)M)?(?:(\d+(?:\.\d+)?)S)?$/
  )
  if (!match) return 0

  const [, days = '0', hours = '0', minutes = '0', seconds = '0'] = match
  return Math.round(
    Number(days) * 86_400 +
      Number(hours) * 3_600 +
      Number(minutes) * 60 +
      Number(seconds)
  )
}

export function parseYouTubeViewCount(value: string | undefined) {
  if (!value || !/^\d+$/.test(value)) return 0

  const parsed = Number(value)
  if (!Number.isFinite(parsed) || parsed < 0) return 0
  return Math.min(Math.floor(parsed), Number.MAX_SAFE_INTEGER)
}

export function isLikelyAiGeneratedVideo(video: YouTubeVideoResource) {
  if (video.status?.containsSyntheticMedia === true) return true

  const snippet = video.snippet
  const metadataText = [
    snippet?.title ?? '',
    snippet?.description ?? '',
    ...(snippet?.tags ?? []),
  ]
    .join(' ')
    .normalize('NFKC')
    .toLocaleLowerCase('ko-KR')

  return AI_GENERATION_TERMS.some((term) =>
    metadataText.includes(term.normalize('NFKC').toLocaleLowerCase('ko-KR'))
  )
}

function getThumbnailUrl(video: YouTubeVideoResource, id: string) {
  const thumbnails = video.snippet?.thumbnails
  const candidates = [
    thumbnails?.maxres,
    thumbnails?.standard,
    thumbnails?.high,
    thumbnails?.medium,
    thumbnails?.default,
  ]

  for (const thumbnail of candidates) {
    if (!thumbnail?.url) continue

    try {
      const url = new URL(thumbnail.url)
      if (url.protocol === 'https:' && url.hostname === 'i.ytimg.com') {
        return url.href
      }
    } catch {
      // Ignore malformed thumbnail metadata and use the canonical fallback.
    }
  }

  return `https://i.ytimg.com/vi/${id}/hqdefault.jpg`
}

function findMatchedChristianTags(tokens: string[]) {
  const candidates = new Set([...CHRISTIAN_TAGS, ...CHRISTIAN_ANCHOR_TAGS])
  return [...candidates]
    .filter((tag) => tokens.includes(normalizeToken(tag)))
    .map((tag) => `#${tag}`)
}

function withoutHashtags(value: string) {
  return value.replace(/#[\p{L}\p{N}_.-]+/gu, ' ')
}

function hasChristianAnchor(value: string) {
  return CHRISTIAN_KOREAN_ANCHOR.test(value.replace(/\s+/g, ''))
    || CHRISTIAN_ENGLISH_ANCHOR.test(value)
    || CHRISTIAN_REFERENCE.test(value)
}

function hasConflictingReligion(fields: string[]) {
  return fields.some((field) => {
    const compact = field.replace(/[^\p{L}\p{N}]+/gu, '')
    return OTHER_RELIGION_KOREAN.some((term) => compact.includes(term))
      || OTHER_RELIGION_ENGLISH.test(field.replace(/[_-]+/g, ' '))
      || [field, ...extractHashtags(field)].some((token) => OTHER_RELIGION_TAG.test(normalizeToken(token)))
  })
}

export function filterChristianShortVideos(
  videos: YouTubeVideoResource[],
  preferredOrder: string[] = []
) {
  const preferredIndex = new Map(preferredOrder.map((id, index) => [id, index]))
  const filtered = videos.flatMap<ChristianShortVideo>((video) => {
    const id = video.id?.trim() ?? ''
    const snippet = video.snippet
    const status = video.status
    const durationSeconds = parseYouTubeDuration(video.contentDetails?.duration)

    if (!isSafeYoutubeId(id) || !snippet?.title || !snippet.channelTitle) return []
    if (durationSeconds < 1 || durationSeconds > MAX_SHORTS_SECONDS) return []
    if (status?.privacyStatus && status.privacyStatus !== 'public') return []
    if (status?.embeddable === false) return []
    if (status?.madeForKids || status?.selfDeclaredMadeForKids) return []
    if (snippet.liveBroadcastContent && snippet.liveBroadcastContent !== 'none') return []
    if (isLikelyAiGeneratedVideo(video)) return []

    const titles = [snippet.title, snippet.localized?.title ?? ''].map(normalizeMetadata)
    const descriptions = [snippet.description ?? '', snippet.localized?.description ?? ''].map(normalizeMetadata)
    const channel = normalizeMetadata(snippet.channelTitle)
    const metadataTags = (snippet.tags ?? []).map(normalizeMetadata)
    const videoText = [...titles, ...descriptions]
    const allMetadata = [...videoText, channel, ...metadataTags]
    if (hasConflictingReligion(allMetadata)) return []
    const hashtags = videoText.flatMap(extractHashtags)
    const tokens = [...metadataTags, ...hashtags].map(normalizeToken).filter(Boolean)
    const hasShortsTag = tokens.some((token) =>
      SHORTS_TAGS.some((shortsTag) => token === normalizeToken(shortsTag))
    )
    const moderationTokens = allMetadata.map(normalizeToken)
    const hasBlockedTerm = moderationTokens.some((text) =>
      BLOCKED_TERMS.some((term) => text.includes(normalizeToken(term)))
    )
    const visibleTitles = titles.map(withoutHashtags)
    const hasStrongTitle = visibleTitles.some(hasChristianAnchor)
    const hasFaithTitle = visibleTitles.some((title) => FAITH_TITLE_CUE.test(title))
    const tagSources = [...titles, ...descriptions].map((field) => extractHashtags(field).map(normalizeToken))
    // A single loosely related tag does not independently corroborate the title.
    // Keep repeated translations from masquerading as multiple sources.
    const sourceTagEvidence = [metadataTags.map(normalizeToken), tagSources[0], tagSources[2]]
    const hasCorroboratingTags = sourceTagEvidence.filter((source) =>
      CHRISTIAN_ANCHOR_TAGS.some((tag) => source.includes(tag))
    ).length >= 2
    const hasSupportingContext = hasCorroboratingTags || hasChristianAnchor(channel)
      || descriptions.map(withoutHashtags).some(hasChristianAnchor)
    // A title must express a Christian topic directly, or a faith topic
    // corroborated by a Christian-specific description/channel/tag.
    // Hashtag stuffing alone cannot override an unrelated title.
    if (!hasShortsTag || hasBlockedTerm || !(hasStrongTitle || (hasFaithTitle && hasSupportingContext))) return []
    const matchedTags = findMatchedChristianTags(tokens)

    return [{
      id,
      title: decodeYouTubeText(snippet.title).slice(0, 160),
      channelId: snippet.channelId?.slice(0, 80) ?? '',
      channelTitle: decodeYouTubeText(snippet.channelTitle).slice(0, 100),
      publishedAt: snippet.publishedAt ?? '',
      durationSeconds,
      thumbnailUrl: getThumbnailUrl(video, id),
      matchedTags: matchedTags.slice(0, 3),
      viewCount: parseYouTubeViewCount(video.statistics?.viewCount),
    }]
  })

  return filtered.sort((left, right) => {
    if (right.viewCount !== left.viewCount) {
      return right.viewCount - left.viewCount
    }

    const leftIndex = preferredIndex.get(left.id) ?? Number.MAX_SAFE_INTEGER
    const rightIndex = preferredIndex.get(right.id) ?? Number.MAX_SAFE_INTEGER
    return leftIndex - rightIndex
  })
}

export async function getChristianShortsFeed(
  pageToken?: string
): Promise<ChristianShortsFeed> {
  const apiKey = process.env.YOUTUBE_API_KEY?.trim()
  if (!apiKey) {
    return {
      status: 'not-configured',
      videos: [],
      message: 'YouTube Shorts 연결을 준비 중입니다.',
    }
  }

  const searchUrl = new URL('https://www.googleapis.com/youtube/v3/search')
  searchUrl.searchParams.set('key', apiKey)
  searchUrl.searchParams.set('part', 'snippet')
  searchUrl.searchParams.set('type', 'video')
  searchUrl.searchParams.set('q', SEARCH_QUERY)
  searchUrl.searchParams.set('maxResults', '50')
  searchUrl.searchParams.set('order', 'viewCount')
  searchUrl.searchParams.set('regionCode', 'KR')
  searchUrl.searchParams.set('relevanceLanguage', 'ko')
  searchUrl.searchParams.set('safeSearch', 'strict')
  searchUrl.searchParams.set('videoDuration', 'short')
  searchUrl.searchParams.set('videoEmbeddable', 'true')
  searchUrl.searchParams.set('videoSyndicated', 'true')
  if (pageToken && isSafeYouTubePageToken(pageToken)) {
    searchUrl.searchParams.set('pageToken', pageToken)
  }

  try {
    const searchResponse = await fetch(searchUrl, {
      next: {
        revalidate: FEED_REVALIDATE_SECONDS,
        tags: ['youtube-christian-shorts-search'],
      },
    })
    const searchPayload = (await searchResponse.json()) as YouTubeSearchResponse
    if (!searchResponse.ok) {
      throw new Error(searchPayload.error?.message ?? 'YouTube Shorts search failed')
    }

    const videoIds = Array.from(new Set(
      (searchPayload.items ?? [])
        .map((item) => item.id?.videoId?.trim() ?? '')
        .filter(isSafeYoutubeId)
    )).slice(0, 50)

    if (videoIds.length === 0) {
      return {
        status: 'ready',
        videos: [],
        nextPageToken: searchPayload.nextPageToken
          && isSafeYouTubePageToken(searchPayload.nextPageToken)
          ? searchPayload.nextPageToken
          : undefined,
      }
    }

    const detailsUrl = new URL('https://www.googleapis.com/youtube/v3/videos')
    detailsUrl.searchParams.set('key', apiKey)
    detailsUrl.searchParams.set('part', 'snippet,contentDetails,status,statistics')
    detailsUrl.searchParams.set('id', videoIds.join(','))
    detailsUrl.searchParams.set('hl', 'ko')

    const detailsResponse = await fetch(detailsUrl, {
      next: {
        revalidate: FEED_REVALIDATE_SECONDS,
        tags: ['youtube-christian-shorts-details'],
      },
    })
    const detailsPayload = (await detailsResponse.json()) as YouTubeVideosResponse
    if (!detailsResponse.ok) {
      throw new Error(detailsPayload.error?.message ?? 'YouTube video details failed')
    }

    return {
      status: 'ready',
      videos: filterChristianShortVideos(detailsPayload.items ?? [], videoIds),
      nextPageToken: searchPayload.nextPageToken
        && isSafeYouTubePageToken(searchPayload.nextPageToken)
        ? searchPayload.nextPageToken
        : undefined,
    }
  } catch (error) {
    console.error(
      'Christian Shorts feed failed:',
      error instanceof Error ? error.message : 'Unknown YouTube API error'
    )
    return {
      status: 'unavailable',
      videos: [],
      message: '영상을 불러오지 못했습니다. 잠시 후 다시 확인해주세요.',
    }
  }
}
